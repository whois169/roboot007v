def rows():
    return [dict(zip(FIELDS, r)) for r in BOM]


def totals():
    t = dict(样品=0, 第二批=0, 以后=0)
    for r in rows():
        if r["批次"] == "样品":
            t["样品"] += r["单价"] * r["样品数"]
            t["第二批"] += r["单价"] * (r["总数"] - r["样品数"])
        elif r["批次"] == "第二批":
            t["第二批"] += r["单价"] * r["总数"]
        elif r["批次"] == "以后":
            t["以后"] += r["单价"] * r["总数"]
    return t


