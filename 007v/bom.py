def write_xlsx():
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "零件清单"
    ws.append(FIELDS + ["样品小计", "总计"])
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="2B3A42")
    for r in rows():
        n = r["单价"] or 0
        ws.append([r[k] for k in FIELDS] + [n * r["样品数"] if r["批次"] == "样品" else 0, n * r["总数"]])
        if r["尺寸状态"] == "★要图":
            ws.cell(ws.max_row, FIELDS.index("尺寸状态") + 1).fill = PatternFill("solid", fgColor="FFE3A3")
    widths = [6, 14, 40, 6, 6, 7, 7, 34, 26, 32, 9, 40, 9, 9]
    for i, w in enumerate(widths):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i + 1)].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")
    t = totals()
    ws.append([])
    ws.append(["", "样品这一批", "", "", "", t["样品"]])
    ws.append(["", "第二批", "", "", "", t["第二批"]])
    ws.freeze_panes = "C2"
    path = os.path.join(ROOT, "docs", "机械狗007v", "采购清单.xlsx")
    wb.save(path)
    return path


def write_json():
    out = os.path.join(HERE, "out", "mfg")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "bom.json"), "w", encoding="utf-8") as f:
        json.dump(dict(rows=rows(), totals=totals()), f, ensure_ascii=False)


