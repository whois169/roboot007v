def svg():
    W, H = 1190, 750
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" class="wiring">']
    for w in WIRES:
        c = COL[w["col"]]
        o.append(f'<polyline points="{" ".join(f"{x},{y}" for x, y in w["pts"])}" fill="none" stroke="{c}" stroke-width="2.4" stroke-linejoin="round"/>')
        x, y = w["pts"][-1]
        o.append(f'<circle cx="{x}" cy="{y}" r="3" fill="{c}"/>')
        if w["label"]:
            o.append(f'<text x="{w["lx"]}" y="{w["ly"]}" class="wl" fill="{c}">{w["label"]}</text>')
    for b in BOXES:
        o.append(f'<g class="bx {b["kind"]}"><rect x="{b["x"]}" y="{b["y"]}" width="{b["w"]}" height="{b["h"]}" rx="3"/>'
                 f'<text x="{b["x"] + 9}" y="{b["y"] + 19}" class="bt">{b["title"]}</text>')
        for i, line in enumerate(b["sub"].split("\n") if b["sub"] else []):
            o.append(f'<text x="{b["x"] + 9}" y="{b["y"] + 36 + i * 15}" class="bs">{line}</text>')
        o.append("</g>")
    # 保险丝盒内容
    for i, t in enumerate(["5A ×4 → 轮子电机（各一路）", "10A ×2 → 髋驱动（两块一路）", "5A → 5V 5.5A（树莓派）", "3A → 5V 3.2A", "3A → 12V（舵机）"]):
        o.append(f'<text x="282" y="{360 + i * 17}" class="bs">{t}</text>')
    lx = 20
    for k, t in LEGEND:
        o.append(f'<rect x="{lx}" y="{H - 26}" width="18" height="4" fill="{COL[k]}"/><text x="{lx + 24}" y="{H - 20}" class="lg">{t}</text>')
        lx += 24 + len(t) * 12 + 18
    o.append("</svg>")
    return "".join(o)


