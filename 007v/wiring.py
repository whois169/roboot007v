def main():
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "wiring.json"), "w", encoding="utf-8") as f:
        json.dump(dict(svg=svg(), pins=PINS), f, ensure_ascii=False)
    print(write_md())


if __name__ == "__main__":
    main()
