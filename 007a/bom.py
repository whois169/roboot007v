def _reuse_rows():
    spec = importlib.util.spec_from_file_location("bom007v", os.path.join(ROOT, "007v", "bom.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    by_name = {r[1]: r for r in m.BOM}
    out = []
    for n in REUSE:
        r = list(by_name[n])
        r[0] = "沿用 007v"
        if n == "台阶测距":
            r[3], r[4] = 1, 2
            r[11] = "前防撞杠 2 个，往下斜看台阶"
        if n == "喇叭":
            r[3], r[4] = 2, 2
            r[11] = "前脸两边的扬声器孔后面，左右各一个"
        if n == "麦克风":
            r[11] = "顶上右前角的麦克风座（会议助手录音、听指令）"
        if n == "树莓派 5":
            r[6] = "沿用"
        out.append(tuple(r))
    return out


def rows():
    return [dict(zip(FIELDS, r)) for r in BOM + _reuse_rows()]


def totals():
    t = dict(样品=0, 第二批=0, 第2步定=0)
    for r in rows():
        n = r["单价"] or 0
        if r["批次"] == "样品":
            t["样品"] += n * r["样品数"]
            t["第二批"] += n * (r["总数"] - r["样品数"])
        elif r["批次"] == "第二批":
            t["第二批"] += n * r["总数"]
        elif r["批次"] == "第2步定":
            t["第2步定"] += n * r["总数"]
    return t


