def rows():
    return [dict(zip(FIELDS, r)) for r in BOM + _reuse_rows()]


def totals():
    t = dict(样品=0, 第二批=0, 第2步定=0)
    for r in rows():
        n = r["单价"] or 0
        if r["批次"] == "样品":
            t["样品"] += n * r["样品数"]
            t["第二批"] += n * (r["总数"] - r["样品数"])
        elif r["批次"] == "第二批":
            t["第二批"] += n * r["总数"]
        elif r["批次"] == "第2步定":
            t["第2步定"] += n * r["总数"]
    return t


