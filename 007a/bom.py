def write_xlsx():
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "零件清单"
    ws.append(FIELDS + ["样品小计", "总计"])
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="2B3A42")
    for r in rows():
        n = r["单价"] or 0
        ws.append([r[k] for k in FIELDS] + [n * r["样品数"] if r["批次"] == "样品" else 0, n * r["总数"]])
        if r["尺寸状态"] == "★要图":
            ws.cell(ws.max_row, FIELDS.index("尺寸状态") + 1).fill = PatternFill("solid", fgColor="FFE3A3")
    for i, w in enumerate([8, 16, 40, 6, 6, 7, 8, 34, 26, 36, 9, 44, 9, 9]):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i + 1)].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")
    t = totals()
    ws.append([])
    ws.append(["", "样品这一批", "", "", "", t["样品"]])
    ws.append(["", "第二批", "", "", "", t["第二批"]])
    ws.append(["", "第 2 步结构件（起）", "", "", "", t["第2步定"]])
    ws.freeze_panes = "C2"
    path = os.path.join(OUT_DIR, "采购清单.xlsx")
    wb.save(path)
    return path


